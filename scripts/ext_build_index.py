"""Tracker Y33: figure index (docs/figures/INDEX.md) and offline gallery (docs/gallery.html).

Sources: results/ext/figure_cards.csv (one card per extended figure, written by save_fig/register_card in every
ext_* script: file, section, task, what it shows, takeaway, source table, script) and the earlier figures in figures/
(September report figures 01-11 with their .txt captions and FIGURE_MANIFEST.csv; tracker figures with the task that
logged them DONE, found in tracker/esr1.log). Nothing is typed by hand: takeaways come from the cards, which the
scripts compute from their result files.
The gallery uses relative image paths (../figures/...), so it works offline as long as docs/ and figures/ sit side by
side (as in the final pack). The interactive plotly scatter is linked from the gallery.
Run from the repo root: PYTHONPATH=. python scripts/ext_build_index.py
"""
import html
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ext_common import RES, ROOT

SECTION_ORDER = ["A. Structural clustering zoo", "B. Chemistry clustering", "C. Why two clusters",
                 "D. Outliers and quality", "E. Experimental metadata", "F. Embeddings and colour-by", "G. Coordinate PCA",
                 "H. B-factors and core", "I. ESR2 and ESR1 vs ESR2", "J. Ligand and conformation",
                 "K. Redundancy and diversity", "L. Time", "M. Robustness", "N. Structure images",
                 "Earlier figures (September report and tracker tasks)"]


def earlier():
    log = (ROOT / "tracker/esr1.log").read_text(encoding="utf8").splitlines()
    man = pd.read_csv(ROOT / "FIGURE_MANIFEST.csv") if (ROOT / "FIGURE_MANIFEST.csv").exists() else pd.DataFrame()
    rows = []
    for p in sorted((ROOT / "figures").glob("*.png")):
        rel = f"figures/{p.name}"
        task, note = "", ""
        for line in log:
            parts = line.split(" | ")
            if len(parts) > 2 and parts[2] == "DONE" and rel in line:
                task = parts[1]
                m = re.search(r"note=(.*)$", line)
                note = m.group(1)[:220] if m else ""
        cap = p.with_suffix(".txt")
        shows = cap.read_text(encoding="utf8").strip().splitlines()[0][:220] if cap.exists() else note
        script = ""
        if len(man) and p.stem in set(man.figure):
            script = man.set_index("figure").loc[p.stem, "python_file"]
            task = task or "September report"
        rows.append(dict(figure=p.stem, file=rel, section=SECTION_ORDER[-1], task=task or "-",
                         shows=shows or "(see tracker log)", takeaway=note or shows, source="(see task)", script=script))
    return pd.DataFrame(rows)


def main():
    cards = pd.read_csv(RES / "figure_cards.csv")
    cards = cards[[(ROOT / f).exists() for f in cards.file]]
    allc = pd.concat([cards, earlier()], ignore_index=True)
    allc["sec_rank"] = allc.section.map({s: i for i, s in enumerate(SECTION_ORDER)}).fillna(99)
    allc = allc.sort_values(["sec_rank", "task", "figure"]).reset_index(drop=True)
    n_png = int(allc.file.str.endswith(".png").sum())
    out = ROOT / "docs/figures"
    out.mkdir(parents=True, exist_ok=True)
    md = [f"# Figure index", "",
          f"{n_png} figures ({int(cards.file.str.endswith('.png').sum())} from the final-run extended analyses, "
          f"{len(allc) - len(cards)} earlier) plus the interactive scatter `docs/interactive_embedding.html`. "
          "Generated by `scripts/ext_build_index.py` from `results/ext/figure_cards.csv`; takeaways are computed by the "
          "producing scripts. Every extended figure also exists as SVG next to the PNG.", ""]
    for sec, g in allc.groupby("section", sort=False):
        md += [f"## {sec}", "", "| figure | task | what it shows | takeaway | source table | script |", "|---|---|---|---|---|---|"]
        for r in g.itertuples():
            cell = lambda s: str(s).replace("|", "/").replace("\n", " ")
            md.append(f"| [{r.figure}](../../{r.file}) | {r.task} | {cell(r.shows)} | {cell(r.takeaway)} | {cell(r.source)} | {cell(r.script)} |")
        md.append("")
    (out / "INDEX.md").write_text("\n".join(md), encoding="utf8")

    css = """
:root{--surface:#fcfcfb;--card:#ffffff;--ink:#0b0b0b;--ink2:#52514e;--muted:#8a8984;--line:#e4e3df;--accent:#2a78d6}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){--surface:#1a1a19;--card:#242422;--ink:#ffffff;--ink2:#c3c2b7;--muted:#9a998f;--line:#383835;--accent:#3987e5}}
:root[data-theme="dark"]{--surface:#1a1a19;--card:#242422;--ink:#ffffff;--ink2:#c3c2b7;--muted:#9a998f;--line:#383835;--accent:#3987e5}
*{box-sizing:border-box}body{margin:0;background:var(--surface);color:var(--ink);font:15px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif}
header{padding:28px 16px 8px;max-width:1200px;margin:auto}h1{font-size:26px;margin:0 0 6px}header p{color:var(--ink2);margin:4px 0}
nav{position:sticky;top:0;background:var(--surface);border-bottom:1px solid var(--line);padding:8px 16px;z-index:2;overflow-x:auto;white-space:nowrap}
nav a{color:var(--accent);text-decoration:none;margin-right:14px;font-size:13px}
main{max-width:1200px;margin:auto;padding:0 16px 40px}h2{margin:34px 0 10px;font-size:20px;border-bottom:1px solid var(--line);padding-bottom:6px}
figure{background:var(--card);border:1px solid var(--line);border-radius:10px;margin:0 0 18px;padding:12px}
figure img{width:100%;height:auto;border-radius:6px;background:#fff;cursor:zoom-in}
figcaption{margin-top:8px}.t{font-weight:600}.m{color:var(--ink2);font-size:13px}.k{margin-top:4px}
.badge{display:inline-block;font-size:12px;color:var(--ink2);border:1px solid var(--line);border-radius:10px;padding:0 8px;margin-right:6px}
a{color:var(--accent)}
"""
    nav = " ".join(f'<a href="#s{i}">{html.escape(s)}</a>' for i, s in enumerate(allc.section.unique()))
    body = []
    for i, (sec, g) in enumerate(allc.groupby("section", sort=False)):
        body.append(f'<h2 id="s{i}">{html.escape(sec)}</h2>')
        for r in g.itertuples():
            src = "../" + r.file
            if not r.file.endswith(".png"):
                body.append(f'<figure><figcaption><span class="badge">{html.escape(str(r.task))}</span>'
                            f'<a class="t" href="{html.escape("../" + r.file)}">{html.escape(r.figure)} (interactive, opens offline)</a>'
                            f'<div class="k">{html.escape(str(r.takeaway))}</div></figcaption></figure>')
                continue
            body.append(f'<figure><a href="{html.escape(src)}"><img loading="lazy" src="{html.escape(src)}" alt="{html.escape(str(r.shows))}"></a>'
                        f'<figcaption><span class="badge">{html.escape(str(r.task))}</span><span class="t">{html.escape(r.figure)}</span>'
                        f'<div class="k">{html.escape(str(r.takeaway))}</div>'
                        f'<div class="m">Shows: {html.escape(str(r.shows))} | Data: {html.escape(str(r.source))} | Script: {html.escape(str(r.script))}</div>'
                        f'</figcaption></figure>')
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>ESR1 Figure Gallery</title><style>{css}</style></head><body>
<header><h1>ESR1 structural diversity: figure gallery</h1>
<p>{n_png} figures, grouped by analysis section. Click a figure to open it full size. Interactive map: <a href="interactive_embedding.html">interactive_embedding.html</a>. Index with sources: <a href="figures/INDEX.md">figures/INDEX.md</a>.</p>
<p class="m">Colours: blue = structural cluster cl7 (agonist-like H12), orange = cl4 (antagonist-like H12), aqua = minor clusters.</p></header>
<nav>{nav}</nav><main>{''.join(body)}</main></body></html>"""
    (ROOT / "docs/gallery.html").write_text(page, encoding="utf8")
    print(n_png, len(cards), len(allc))


if __name__ == "__main__":
    main()
