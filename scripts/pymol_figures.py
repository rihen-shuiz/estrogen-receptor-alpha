"""Tracker F01 / F02: PyMOL scripts for the medoid overlay and the ESR1/ESR2 displacement map.

F01 figures/medoids.pml: loads every S12 medoid chain (results/medoids.csv), moves it with its saved S03 core-fit
  transform (results/alignment/alignment_transforms.json, the same superposition as the analysis, no refit), shows
  cartoons and colours H12 (h12_range, mapped to author numbering per chain through residue_mapping.csv).
F02 figures/displacement_structure.pml: writes the per-position median ESR1/ESR2 displacement (E07,
  results/displacement_matrix.csv, median over the matched pairs) into the B-factor column of the S12 medoid of the
  largest cluster and colours blue-white-red over 0-3 A; positions with no value are grey.
Both scripts are self-contained (values embedded), load mmCIFs from data/raw (scripts/fetch_data.py) relative to the
repo root and write their PNG next to the .pml. Run from the repo root: pymol -cq figures/medoids.pml
This generator downloads missing mmCIFs, writes both .pml files and, when a PyMOL executable is given with --pymol or
the PYMOL environment variable, renders the PNGs.
Run from the repo root: PYTHONPATH=. python scripts/pymol_figures.py [--pymol /path/to/pymol]
"""
import argparse
import json
import os
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

from esr_analysis.download_structures import download_one

ROOT = Path(__file__).resolve().parents[1]
SETTINGS = json.loads((ROOT / "esr_analysis/resources/config/analysis_settings.json").read_text())
H12 = range(SETTINGS["h12_range"][0], SETTINGS["h12_range"][1] + 1)
CATEGORICAL = ["0x2a78d6", "0xeb6834", "0x1baf7a", "0xeda100", "0xe87ba4", "0x008300", "0x4a3aa7"]  # palette slots 1-7

HEADER = """# Generated by scripts/pymol_figures.py ({task}). Run from the repo root: pymol -cq {name}
reinitialize
set cif_use_auth, 1
set matrix_mode, 0
set orthoscopic, 1
set ray_shadows, 0
set antialias, 2
set opaque_background, 1
bg_color white
set cartoon_fancy_helices, 1
viewport 1400, 1050
"""


def matrix_4x4(info):
    """S03 row-vector transform (x - cm) @ R + cr as a PyMOL homogeneous column-vector matrix."""
    r = np.array(info["rotation"])
    t = np.array(info["reference_centroid"]) - np.array(info["mobile_centroid"]) @ r
    m = np.eye(4)
    m[:3, :3], m[:3, 3] = r.T, t
    return [round(float(v), 8) for v in m.ravel()]


def author_residues(mapping, chain_key, positions):
    rows = mapping[(mapping.chain_key == chain_key) & mapping.has_ca & mapping.esr1_position.isin(list(positions))]
    return {int(p): f"{int(a)}{'' if str(i) in ('?', '.', 'nan') else i}"
            for p, a, i in zip(rows.esr1_position, rows.auth_seq_id, rows.insertion_code)}


def load_lines(obj, pdb_id, auth, label, transform):
    return [f"load data/raw/{pdb_id}.cif, raw_{obj}",
            f"create {obj}, raw_{obj} and polymer and chain {auth} and segi {label}",
            f"delete raw_{obj}",
            f"python\ncmd.transform_object('{obj}', {transform}, state=1, homogenous=1, transpose=0)\npython end"]


def medoids_pml(medoids, chains, transforms, mapping):
    lines = [HEADER.format(task="F01", name="figures/medoids.pml")]
    for colour, row in zip(CATEGORICAL, medoids.itertuples()):
        chain = chains.loc[row.chain_key]
        obj = f"c{row.cluster}_{row.entry_id}_{chain.label_asym_id}"
        lines += load_lines(obj, row.entry_id, chain.auth_asym_id, chain.label_asym_id, matrix_4x4(transforms[row.chain_key]))
        lines.append(f"color {colour}, {obj}")
        h12 = author_residues(mapping, row.chain_key, H12)
        if h12:
            lines.append(f"color 0xe34948, {obj} and resi {'+'.join(h12.values())}")
        lines.append(f"# cluster {row.cluster}: {row.chain_key}, {row.cluster_size} chains; H12 {SETTINGS['h12_range']} = author resi {'+'.join(h12.values()) or 'not modelled'}")
    lines += ["hide everything", "show cartoon", "set cartoon_transparency, 0.15", "orient", "turn x, -90",
              "ray 1400, 1050", "png figures/medoids.png, dpi=150"]
    return "\n".join(lines) + "\n"


def displacement_pml(medoid, chains, transforms, mapping, median):
    chain = chains.loc[medoid.chain_key]
    obj = f"m_{medoid.entry_id}_{chain.label_asym_id}"
    residues = author_residues(mapping, medoid.chain_key, median.dropna().index)
    values = {residues[p]: round(float(median[p]), 3) for p in residues}
    lines = [HEADER.format(task="F02", name="figures/displacement_structure.pml")]
    lines += load_lines(obj, medoid.entry_id, chain.auth_asym_id, chain.label_asym_id, matrix_4x4(transforms[medoid.chain_key]))
    lines += [f"# median ESR2-vs-ESR1 C-alpha displacement (E07, {len(values)} positions) written into b; others b = -1",
              f"alter {obj}, b=-1",
              "python",
              f"values = {values}",
              f"cmd.alter('{obj}', 'b = values.get(resi, -1.0)', space={{'values': values}})",
              "python end",
              "hide everything", f"show cartoon, {obj}",
              f"spectrum b, blue_white_red, {obj} and b > -0.5, minimum=0, maximum=3",
              f"color grey70, {obj} and b < -0.5",
              "set cartoon_putty_scale_min, 0", "orient", "turn x, -90",
              "ray 1400, 1050", "png figures/displacement_structure.png, dpi=150"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pymol", default=os.environ.get("PYMOL"))
    args = parser.parse_args()

    medoids = pd.read_csv(ROOT / "results/medoids.csv").sort_values("cluster_size", ascending=False)
    chains = pd.read_csv(ROOT / "results/lbd_extract/receptor_chains.csv",
                         usecols=["chain_key", "label_asym_id", "auth_asym_id"]).set_index("chain_key")
    transforms = json.loads((ROOT / "results/alignment/alignment_transforms.json").read_text())
    mapping = pd.read_csv(ROOT / "results/lbd_extract/residue_mapping.csv", low_memory=False,
                          usecols=["chain_key", "esr1_position", "has_ca", "auth_seq_id", "insertion_code"])
    mapping = mapping[mapping.chain_key.isin(medoids.chain_key)]
    for pdb_id in medoids.entry_id.unique():
        ok, how = download_one(pdb_id, ROOT / "data/raw" / f"{pdb_id}.cif")
        if not ok:
            raise RuntimeError(f"{pdb_id}: {how}")

    (ROOT / "figures/medoids.pml").write_text(medoids_pml(medoids, chains, transforms, mapping))
    median = pd.read_csv(ROOT / "results/displacement_matrix.csv", index_col="esr1_pos").median(axis=1)
    largest = medoids.iloc[0]
    (ROOT / "figures/displacement_structure.pml").write_text(displacement_pml(largest, chains, transforms, mapping, median))
    print(f"wrote figures/medoids.pml ({len(medoids)} medoids) and figures/displacement_structure.pml "
          f"({largest.chain_key}, cluster {largest.cluster})")
    if not args.pymol:
        print("no PyMOL executable (--pymol or PYMOL); PNGs not rendered")
        return
    for name in ["medoids", "displacement_structure"]:
        result = subprocess.run([args.pymol, "-cq", f"figures/{name}.pml"], cwd=ROOT, capture_output=True, text=True, timeout=300)
        (ROOT / f"figures/{name}.log").write_text(result.stdout + result.stderr)
        if result.returncode or not (ROOT / f"figures/{name}.png").is_file():
            raise RuntimeError(f"PyMOL failed for {name}; see figures/{name}.log")
        print(f"rendered figures/{name}.png")


if __name__ == "__main__":
    main()
